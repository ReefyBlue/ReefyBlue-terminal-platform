"""Regenerate the shipped v2 layouts from the builder: ``uv run python scripts/gen_layouts.py``.

Writes ``terminal_mv_small.yaml`` (test layout) and ``terminal_mv.yaml`` (demo) at the repo root.
Do not hand-edit those files; ``tests/model/test_layout_builder.py`` checks they match.
"""
from __future__ import annotations

from pathlib import Path

import yaml
from terminal_model.layout_builder import standard_terminal, to_yaml_dict

ROOT = Path(__file__).resolve().parents[1]

LAYOUTS = {
    "terminal_mv_small.yaml": {"name": "mv_small", "quay_length_m": 400, "n_berths": 1, "n_sts": 3,
                               "n_blocks": 4, "n_agv_buffers_per_sts": 4},
    "terminal_mv.yaml": {"name": "mv", "quay_length_m": 1200, "n_berths": 2, "n_sts": 8, "n_blocks": 24},
}

HEADER = "# Generated by scripts/gen_layouts.py from terminal_model.layout_builder - do not edit.\n"


def main() -> None:
    for fname, kwargs in LAYOUTS.items():
        text = HEADER + yaml.safe_dump(to_yaml_dict(standard_terminal(**kwargs)), sort_keys=False)
        (ROOT / fname).write_text(text)
        print(f"wrote {fname}")


if __name__ == "__main__":
    main()
